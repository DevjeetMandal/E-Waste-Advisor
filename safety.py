"""
Deterministic safety hints. These are NOT generated by the LLM and NOT from the
rules documents - they are short, widely-published general precautions, shown
in their own clearly-labelled box. Keeping them rule-based means the most
safety-critical text can never be hallucinated.
"""

import re


def _has(text, words):
    return any(re.search(r"(?<![a-z0-9])" + re.escape(w) + r"(?![a-z0-9])", text) for w in words)


BATTERY = ["battery", "batteries", "power bank", "li-ion", "lithium"]
DAMAGED = ["swollen", "swelling", "bulging", "puffed", "leaking", "leak", "hot", "smoking",
           "burning", "damaged", "punctured", "crushed", "melted", "overheating"]
CFL = ["cfl", "fluorescent", "tube light", "tubelight"]
BROKEN = ["broken", "shattered", "cracked", "smashed"]
DATA_DEVICES = ["phone", "mobile", "smartphone", "laptop", "computer", "desktop", "tablet",
                "hard disk", "hard drive", "ssd", "pen drive", "smartwatch"]
REFRIGERANT = ["refrigerator", "fridge", "air conditioner", "ac", "freezer", "water cooler"]


def safety_flags(description):
    text = (description or "").lower()
    flags = []

    if _has(text, BATTERY) and _has(text, DAMAGED):
        flags.append({
            "level": "urgent",
            "title": "Damaged battery: fire risk",
            "advice": "Stop using and charging it. Do not press, puncture or open it. Keep it away "
                      "from flammable items, ideally in a metal or ceramic container, and hand it to "
                      "a battery collection point soon. Never put it in household trash.",
        })
    if _has(text, CFL) and _has(text, BROKEN):
        flags.append({
            "level": "urgent",
            "title": "Broken CFL/tube: mercury vapour",
            "advice": "Ventilate the room for 10-15 minutes and avoid using a vacuum cleaner. Pick up "
                      "fragments with stiff paper, seal them in a bag or jar, and take them to a "
                      "collection point.",
        })
    if _has(text, DATA_DEVICES):
        flags.append({
            "level": "info",
            "title": "Protect your data first",
            "advice": "Back up what you need, sign out of your accounts and factory-reset the device. "
                      "For laptops and drives holding sensitive data, remove the storage before handing "
                      "the device over.",
        })
    if _has(text, REFRIGERANT):
        flags.append({
            "level": "info",
            "title": "Do not dismantle it yourself",
            "advice": "Cooling appliances contain refrigerant gas and oils. Cutting pipes or the "
                      "compressor releases them. Use a manufacturer take-back or an authorised recycler.",
        })
    return flags
